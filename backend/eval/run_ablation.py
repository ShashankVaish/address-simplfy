"""Run one or more ablation configurations against a split.

The argument this table makes is the important one. Configuration B -- a single
LLM call over the raw string -- is the entire product most competing teams will
submit. Showing the gap from B to E is what demonstrates that the architecture
was necessary rather than decorative. Which means configuration A has to be
measured honestly, including on Day 1 when it is bad: "we went from 0.58 to
0.91" only exists if Thursday wrote down 0.58.

    python -m eval.run_ablation --split dev --stacks A
    python -m eval.run_ablation --split test --stacks A B C D E   # ONCE, at the end
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "layers/common/python"))

from eval.metrics import evaluate, format_report
from patasetu import gazetteer
from patasetu.config import load as load_config
from patasetu.pipeline import Stack, StageUnavailable, resolve

STACK_LABELS: dict[str, str] = {
    "A": "Deterministic regex + gazetteer only",
    "B": "A + single LLM call, no retrieval",
    "C": "B + BM25 landmark retrieval",
    "D": "C + vector retrieval + geo filter",
    "E": "D + warmed landmark graph (full system)",
}


def load_split(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.open(encoding="utf-8")]


def truth_for(row: dict[str, Any]) -> dict[str, Any]:
    """Flatten a gold row into what the metrics expect."""
    truth = dict(row["truth"])
    truth["geo"] = row.get("geo")
    return truth


def run_stack(
    stack: Stack, rows: list[dict[str, Any]], threshold: float
) -> tuple[dict[str, Any] | None, str]:
    cfg = load_config()
    predictions: list[dict[str, Any]] = []

    start = time.perf_counter()
    for row in rows:
        try:
            result = resolve(row["raw"], stack=stack, cfg=cfg)
        except StageUnavailable as exc:
            return None, str(exc)
        predictions.append(result.model_dump(mode="json"))
    wall_ms = (time.perf_counter() - start) * 1000.0

    truths = [truth_for(r) for r in rows]
    m = evaluate(predictions, truths, threshold=threshold)

    report = format_report(m, title=f"configuration {stack.value}")
    row_out = m.as_row()
    row_out["stack"] = stack.value
    row_out["label"] = STACK_LABELS[stack.value]
    row_out["wall_ms_total"] = round(wall_ms, 1)
    row_out["wall_ms_per_address"] = round(wall_ms / max(1, len(rows)), 3)
    row_out["latency_p50_ms"] = m.latency_p50_ms
    row_out["latency_p95_ms"] = m.latency_p95_ms
    row_out["notes"] = m.notes
    return row_out, report


def write_markdown(results: list[dict[str, Any]], split: str, out: Path) -> None:
    """Render the five-row ablation table, leaving unrun rows visibly empty."""
    by_stack = {r["stack"]: r for r in results}

    lines = [
        "# Ablation results",
        "",
        f"Split: **{split}**  ·  generated by `eval/run_ablation.py`",
        "",
        "Configurations are cumulative: each adds one stage to the one above it.",
        "A row with `--` has not been run yet; it is never filled with the",
        "numbers of a weaker configuration.",
        "",
        "| Config | What it is | Field F1 | Exact match | Geo median | Auto-resolve | Clarify | P@thresh |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key in ("A", "B", "C", "D", "E"):
        label = STACK_LABELS[key]
        r = by_stack.get(key)
        if r is None:
            lines.append(f"| **{key}** | {label} | -- | -- | -- | -- | -- | -- |")
            continue
        geo = f"{r['geo_median_m']:,.0f} m" if r["geo_median_m"] is not None else "--"
        lines.append(
            f"| **{key}** | {label} | {r['field_f1']:.3f} | {r['exact_match']:.3f} "
            f"| {geo} | {r['auto_resolution_rate']:.1%} "
            f"| {r['clarification_rate']:.1%} | {r['precision_at_threshold']:.3f} |"
        )

    lines += ["", "## Notes", ""]
    for key in ("A", "B", "C", "D", "E"):
        r = by_stack.get(key)
        if r is None:
            continue
        lines.append(
            f"**{key}** — n={r['n']}, {r['wall_ms_per_address']:.2f} ms/address"
        )
        for note in r.get("notes", []):
            lines.append(f"  - {note}")
        lines.append("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--split", choices=("dev", "test"), default="dev")
    ap.add_argument("--stacks", nargs="+", default=["A"], choices=list(STACK_LABELS))
    ap.add_argument("--data-dir", type=Path, default=Path("eval/data"))
    ap.add_argument("--out", type=Path, default=Path("../docs/results/ablation.md"))
    ap.add_argument("--json-out", type=Path, default=Path("eval/data/ablation.json"))
    ap.add_argument("--threshold", type=float, default=None)
    args = ap.parse_args()

    path = args.data_dir / f"gold_{args.split}.jsonl"
    if not path.exists():
        print(f"error: {path} not found. Run scripts.make_gold first.", file=sys.stderr)
        return 1

    rows = load_split(path)
    threshold = (
        args.threshold
        if args.threshold is not None
        else load_config().thresholds.resolved_at
    )

    if args.split == "test":
        print("!" * 72)
        print("Running the TEST split. This is meant to happen exactly once,")
        print("at the end (FR-40). Do not tune anything after reading these.")
        print("!" * 72)
        print()

    gazetteer.warm()

    results: list[dict[str, Any]] = []
    for name in args.stacks:
        stack = Stack(name)
        row, report = run_stack(stack, rows, threshold)
        print(report)
        print()
        if row is None:
            print(f"configuration {name}: NOT RUN -- {report}")
            print()
            continue
        results.append(row)

    if results:
        write_markdown(results, args.split, args.out)
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(
            json.dumps(
                {"split": args.split, "threshold": threshold, "rows": results}, indent=2
            ),
            encoding="utf-8",
        )
        print(f"wrote {args.out} and {args.json_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
